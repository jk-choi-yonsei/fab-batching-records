"""confirm_tables.py renders paper/tables/{policies,numbers}.tex from final/confirm/results.json; rendered
again into a temporary directory, the two files equal the tracked ones byte for byte.

The two header lines carry no wall-clock time: the second quotes meta.generated of the results file, so it is part
of the comparison. The tracked files are compared with CRLF read as LF, since a Windows checkout with
core.autocrlf=true writes CRLF while the generator always writes LF.

Run from fabhybrid/smt2020:  python -B -m pytest tests/test_confirm_tables_regenerates.py -q -p no:cacheprovider
"""
import os
import sys

import pytest

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE)
import confirm_tables  # noqa: E402

NAMES = ("policies.tex", "numbers.tex")


@pytest.mark.skipif(not os.path.exists(confirm_tables.RESULTS), reason="no final/confirm/results.json")
@pytest.mark.skipif(not all(os.path.exists(os.path.join(confirm_tables.OUT, n)) for n in NAMES),
                    reason="no paper/tables (a copy without the manuscript, such as the code package)")
def test_tables_regenerate_byte_for_byte(tmp_path, monkeypatch):
    monkeypatch.setattr(sys, "argv", ["confirm_tables.py", "--out", str(tmp_path)])
    confirm_tables.main()
    for name in NAMES:
        with open(tmp_path / name, "rb") as f:
            got = f.read()
        with open(os.path.join(confirm_tables.OUT, name), "rb") as f:
            tracked = f.read().replace(b"\r\n", b"\n")
        assert b"\r" not in got, name
        head = got.split(b"\n")[:2]
        assert head[0] == b"% generated by fabhybrid/smt2020/confirm_tables.py from experiments/smt2020/final/confirm/results.json"
        assert head[1].startswith(b"% confirm results of ") and head[1].endswith(b"; do not edit by hand")
        assert got == tracked, f"{name} differs from paper/tables/{name}"
