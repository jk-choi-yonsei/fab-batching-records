"""Table 4 of the paper: agreement of the tables fitted from the timeout and minimum-batch-size rules' records at
each price with the tables at the paper's price, as the share of the free decisions of the records at which the two
take the same action. With --full, the same table over every setting of the fit (gamma, n0, the bin boundaries) is
written as well, for the repository; the paper gives those as a range in Section 5.3.

  python sensitivity_table.py                 -> paper/tables/sensitivity.tex (the price rows, Table 4)
  python sensitivity_table.py --full OUT.tex  -> also the table over every setting, to OUT.tex

Sources: experiments/smt2020/final/paperfacts/rule_tables_summary.json (price, gamma, n0; 2026-10-03) and
experiments/smt2020/final/binedges003/summary.json (bin boundaries at beta 0.003; 2026-10-09).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from confirm_tables import interact_table  # noqa: E402

FINAL = os.path.normpath(os.path.join(HERE, "..", "..", "experiments", "smt2020", "final"))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "paper", "tables", "sensitivity.tex"))
COLS = [("HVLM", "timeout"), ("HVLM", "mbs3"), ("LVHM", "timeout"), ("LVHM", "mbs3")]
PRICES = ["0.0005", "0.001", "0.0016", "0.002", "0.0025", "0.004", "0.005", "0.0075", "0.01", "0.015", "0.02"]
GAMMAS = ["0.8", "0.95", "0.99"]
N0S = ["1", "3", "30"]
# the bin boundaries of the paper, and each variant as (key, axis, its boundaries, or the factor they are scaled by);
# the row label is made from these and checked against the boundaries that were run (summary.json), so that a label
# cannot drift from the run ("scaled by 1.5" was printed for Ah, run at 0.5, 2, 6 h, until 2026-10-19)
REF = {"tightest": [0.25, 0.5, 1, 2, 4], "nxt": [0.25, 1, 3]}
BINS = [("Rc", "tightest", [0.5, 1, 2, 4], None), ("Rf", "tightest", [0.25, 0.5, 0.75, 1, 1.5, 2, 3, 4], None),
        ("Rl", "tightest", None, 0.75), ("Rh", "tightest", None, 1.5),
        ("Ac", "nxt", [0.5, 2], None), ("Af", "nxt", [0.25, 0.5, 1, 2, 3, 6], None),
        ("Al", "nxt", None, 0.5), ("Ah", "nxt", None, 2)]
HEADING = {"tightest": "Residual boundaries", "nxt": "Arrival boundaries"}
HEAD = r"""    & \multicolumn{2}{c}{HVLM} & \multicolumn{2}{c}{LVHM} \\
    \cmidrule(lr){2-3} \cmidrule(l){4-5}
    LABEL & Timeout & Min.\ batch size & Timeout & Min.\ batch size \\"""
COMMENT = "% generated by fabhybrid/smt2020/sensitivity_table.py; do not edit by hand\n"


def hours(xs):
    return ", ".join(f"{x:g}" for x in xs) + "~h"


def pct(x):
    return f"{x:.1f}"


def load():
    s = json.load(open(os.path.join(FINAL, "paperfacts", "rule_tables_summary.json"), encoding="utf-8"))
    b = json.load(open(os.path.join(FINAL, "binedges003", "summary.json"), encoding="utf-8"))
    variants = b["variants"]
    for key, axis, edges, factor in BINS:   # the boundaries printed must be the ones that were run
        v = variants[key]
        other = "nxt" if axis == "tightest" else "tightest"
        run = edges if edges is not None else [factor * x for x in REF[axis]]
        assert v[other] is None and len(v[axis]) == len(run), key
        assert all(abs(a - b) < 1e-9 for a, b in zip(v[axis], run)), (key, v[axis], run)
    return s, b


def agree(s, fab, kind, group, value):
    return 100.0 - 100.0 * s[fab][kind][group][value]["share_decisions"]


def price_rows(s):
    return [(p, [agree(s, f, k, "price", p) for f, k in COLS]) for p in PRICES]


def other_rows(s, b):
    rows = [("\\emph{Discount $\\gamma$ per hour (reference 0.9)}", None)]
    rows += [(g, [agree(s, f, k, "gamma", g) for f, k in COLS]) for g in GAMMAS]
    rows.append(("\\emph{Required count and shrinkage weight $n_0$ (reference 10)}", None))
    rows += [(n, [agree(s, f, k, "n0", n) for f, k in COLS]) for n in N0S]
    for axis in ("tightest", "nxt"):
        rows.append((f"\\emph{{{HEADING[axis]} (reference {hours(REF[axis])})}}", None))
        for key, ax, edges, factor in BINS:
            if ax == axis:
                desc = hours(edges) if edges is not None else f"scaled by {factor:g}"
                rows.append((desc, [b["per_fab_kind"][f"{f}_{k}"]["rows"][key]["agree_pct"] for f, k in COLS]))
    return rows


def body(rows, indent):
    out = []
    for name, vals in rows:
        if vals is None:
            out.append(f"    \\multicolumn{{5}}{{@{{}}l}}{{{name}}} \\\\")
        else:
            out.append(f"    {indent}{name} & " + " & ".join(pct(v) for v in vals) + " \\\\")
    return "\n".join(out)


def price_table(s):
    """Table 4: the price rows, in the paper's table layout"""
    cap = (r"Share (\%) of the free decisions of the records at which the table refitted at each price takes the "
           r"action of the table at $\beta = 0.003$, for the records of the timeout and minimum-batch-size rules.")
    return interact_table(cap, "tab:sensitivity", r"@{}l cccc@{}", HEAD.replace("LABEL", r"Price $\beta$"),
                          body(price_rows(s), ""), "6pt", "", COMMENT)


def full_table(s, b):
    """every setting of the fit, in the same layout, for the repository"""
    cap = (r"Share (\%) of the free decisions of the records at which the table refitted with one setting of the fit "
           r"changed takes the action of the table at the paper's settings, for the records of the timeout and "
           r"minimum-batch-size rules.")
    rows = [("\\emph{Price $\\beta$ (reference 0.003)}", None)] + price_rows(s) + other_rows(s, b)
    return interact_table(cap, "tab:sensitivity-full", r"@{}l cccc@{}", HEAD.replace("LABEL", "Setting"),
                          body(rows, "\\quad "), "6pt", "", COMMENT)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default=OUT, help="where Table 4 goes (default: paper/tables/sensitivity.tex)")
    ap.add_argument("--full", default=None, help="also write the table over every setting of the fit to this file")
    a = ap.parse_args()
    s, b = load()
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(price_table(s))
    print("wrote", a.out, f"({len(PRICES)} rows)")
    if a.full:
        with open(a.full, "w", encoding="utf-8", newline="\n") as f:
            f.write(full_table(s, b))
        print("wrote", a.full)


if __name__ == "__main__":
    main()
